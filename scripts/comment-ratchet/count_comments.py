#!/usr/bin/env python3
"""Reviewable-comment ratchet for the polyrepo (ADR-comments-ratchet).

Counts comment lines per code repo and compares them with a recorded baseline.
It fails only when a repo has more reviewable comments than its baseline, so
deletions always pass and a new comment must be reviewed before its count is
folded into the baseline.

This is a standalone pre-merge check. It intentionally configures no CI hook;
a CI job can call the same command without changing this script.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_ROOT = SCRIPT_DIR.parents[2]
DEFAULT_BASELINE = SCRIPT_DIR / "comment-baseline.json"

# Code repos only. Documentation and state-for-agents hold prose and task logs,
# not reviewable source comments, and the ratchet must not count its own script.
REPOS: dict[str, str] = {
    "analytics-svc": "analytics-svc",
    "auth-svc": "auth-svc",
    "cart-svc": "cart-svc",
    "catalog-svc": "catalog-svc",
    "cms-svc": "cms-svc",
    "ecom-contracts": "ecom-contracts",
    "ecom-infra": "ecom-infra",
    "ecom-messaging": "ecom-messaging",
    "import-svc": "import-svc",
    "notify-svc": "notify-svc",
    "order-svc": "order-svc",
    "search-svc": "search-svc",
    "storefront-ui": "frontend/storefront",
    "admin-app": "frontend/admin",
}

SLASH_STYLE = {".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"}
HASH_STYLE = {".py", ".sh", ".ps1", ".yml", ".yaml"}
DASH_STYLE = {".sql"}

SKIP_DIRS = {
    "node_modules", "dist", "build", "out", "coverage", ".next", ".turbo",
    ".git", ".cache", "__pycache__", ".venv", "venv", "vendor", "generated",
}
SKIP_NAMES = {"pnpm-lock.yaml", "package-lock.json", "yarn.lock", "bun.lockb"}
SKIP_SUFFIXES = (".min.js", ".min.css", ".d.ts", ".map", ".snap")
GENERATED_MARKERS = (
    "@generated", "auto-generated", "auto generated", "generated by",
    "do not edit", "code generated",
)

# Comments that are sanctioned by ADR-comments / AGENTS.md §5: they carry a
# reason the code cannot show, record an ADR pointer, or satisfy a lint/TS
# directive. They are not removable by choice, so they stay out of the count.
SANCTIONED = (
    re.compile(r"\breason\s*:", re.I),
    re.compile(r"\bwhy\s*:", re.I),
    re.compile(r"\badr-[a-z0-9_-]+\s*:", re.I),
    re.compile(
        r"eslint|@ts-|prettier|vite-|c8-|istanbul|noinspection|"
        r"type:\s*ignore|@jsx|@deprecated",
        re.I,
    ),
    re.compile(r"!important|console\s*\.|localstorage|\?\?|emoji", re.I),
)


@dataclass(frozen=True)
class CommentBlock:
    lines: int
    text: str


def comment_blocks(text: str, style: str) -> list[CommentBlock]:
    """Split source text into comment blocks, ignoring comment markers in strings.

    A tiny character scanner is enough here: it treats quotes as opaque so a
    URL such as ``https://...`` is not mistaken for a comment. Regex literals
    and nested ``${}`` template expressions are the known simplifications; they
    cannot create a false *decrease*, only a rare extra counted line, which a
    baseline review catches.
    """
    blocks: dict[int, dict[int, str]] = {}
    next_id = 0
    state = "code"
    quote = ""
    block_id = -1
    line = 1
    i = 0
    size = len(text)

    def record(target_id: int, line_no: int, chunk: str) -> None:
        per_line = blocks.setdefault(target_id, {})
        per_line[line_no] = per_line.get(line_no, "") + chunk

    while i < size:
        ch = text[i]
        after = text[i + 1] if i + 1 < size else ""

        if ch == "\n":
            if state == "line":
                state = "code"
            line += 1
            i += 1
            continue

        if state == "line":
            record(block_id, line, ch)
            i += 1
            continue

        if state == "block":
            if ch == "*" and after == "/":
                record(block_id, line, "/")
                state = "code"
                i += 2
                continue
            record(block_id, line, ch)
            i += 1
            continue

        if state == "string":
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                state = "code"
            i += 1
            continue

        # Code state: only here can a new comment start.
        if style == "slash" and ch == "/" and after in ("/", "*"):
            next_id += 1
            block_id = next_id
            state = "line" if after == "/" else "block"
            record(block_id, line, ch + after)
            i += 2
            continue
        if style == "hash" and ch == "#":
            next_id += 1
            block_id = next_id
            state = "line"
            record(block_id, line, ch)
            i += 1
            continue
        if style == "dash" and ch == "-" and after == "-":
            next_id += 1
            block_id = next_id
            state = "line"
            record(block_id, line, ch + after)
            i += 2
            continue
        if ch in "\"'`":
            state = "string"
            quote = ch

        i += 1

    return [
        CommentBlock(
            lines=len(per_line),
            text=" ".join(per_line[line_no] for line_no in sorted(per_line)),
        )
        for per_line in blocks.values()
    ]


def is_sanctioned(block: CommentBlock) -> bool:
    return any(pattern.search(block.text) for pattern in SANCTIONED)


def is_generated(text: str) -> bool:
    head = text[:4000].lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def source_files(repo_dir: Path):
    """Yield (path, style) for non-generated source files under a repo."""
    for root, dirs, files in os.walk(repo_dir):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for name in sorted(files):
            if name in SKIP_NAMES or name.endswith(SKIP_SUFFIXES):
                continue
            suffix = Path(name).suffix.lower()
            style = (
                "slash" if suffix in SLASH_STYLE
                else "hash" if suffix in HASH_STYLE
                else "dash" if suffix in DASH_STYLE
                else None
            )
            if style is not None:
                yield Path(root) / name, style


def count_repo(root: Path, relative: str) -> int | None:
    """Count reviewable comment lines in one repo, or None if it is absent."""
    repo_dir = root / relative
    if not repo_dir.is_dir():
        return None
    total = 0
    for path, style in source_files(repo_dir):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if is_generated(text):
            continue
        total += sum(
            block.lines
            for block in comment_blocks(text, style)
            if not is_sanctioned(block)
        )
    return total


def count_repos(root: Path, repos: dict[str, str]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for name, relative in repos.items():
        count = count_repo(root, relative)
        if count is not None:
            counts[name] = count
    return counts


def violations(counts: dict[str, int], baseline: dict[str, int]) -> list[tuple[str, int, int]]:
    """Return (repo, baseline, current) for every repo that rose above baseline."""
    return sorted(
        (name, baseline.get(name, 0), current)
        for name, current in counts.items()
        if current > baseline.get(name, 0)
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=DEFAULT_ROOT,
        help="polyrepo root (default: derived from this script's location)",
    )
    parser.add_argument(
        "--baseline", type=Path, default=DEFAULT_BASELINE,
        help="path to the JSON baseline",
    )
    parser.add_argument(
        "--update-baseline", action="store_true",
        help="record current counts as the new baseline (review additions first)",
    )
    parser.add_argument("--json", action="store_true", help="emit machine-readable output")
    parser.add_argument("--repo", action="append", help="limit the check to named repos")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    root = args.root.resolve()

    repos = REPOS
    if args.repo:
        unknown = sorted(set(args.repo) - set(REPOS))
        if unknown:
            print(f"unknown repo(s): {', '.join(unknown)}", file=sys.stderr)
            return 2
        repos = {name: REPOS[name] for name in args.repo}

    counts = count_repos(root, repos)
    if not counts:
        print(f"no configured repos found under {root}", file=sys.stderr)
        return 2

    if args.update_baseline:
        payload = {
            "version": 1,
            "description": (
                "Maximum reviewable comment lines per repo. Regenerate only "
                "after each added comment has been reviewed against ADR-comments."
            ),
            "repos": dict(sorted(counts.items())),
        }
        args.baseline.parent.mkdir(parents=True, exist_ok=True)
        args.baseline.write_text(
            json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        if not args.json:
            print(f"baseline written to {args.baseline}")
        return 0

    if not args.baseline.is_file():
        print(f"baseline not found: {args.baseline}", file=sys.stderr)
        return 2
    try:
        baseline = json.loads(args.baseline.read_text(encoding="utf-8"))["repos"]
    except (OSError, ValueError, KeyError) as exc:
        print(f"unreadable baseline: {exc}", file=sys.stderr)
        return 2

    bad = violations(counts, baseline)
    if args.json:
        print(json.dumps({"counts": counts, "violations": bad}, sort_keys=True))
    else:
        for name in sorted(counts):
            base = baseline.get(name, 0)
            flag = "RAISED" if (name, base, counts[name]) in bad else "ok"
            print(f"{name:16} baseline={base:5} current={counts[name]:5} {flag}")
        for name, base, current in bad:
            print(
                f"FAIL {name}: {current} reviewable comments > baseline {base}",
                file=sys.stderr,
            )
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
